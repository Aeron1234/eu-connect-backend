import express from "express";
import { verifyUser } from "../../../middleware/verifyUser.js";
import { verifyRole } from "../../../middleware/verifyRole.js";
import { generalLimiter, mediumLimiter, uploadLimiter } from "../../../middleware/rateLimiter.js";
import { acceptFeedbackAttachments } from "../../../middleware/multipart-uploads.js";
import { listFeedback, getFeedback, getFeedbackInterns, createFeedback, replyFeedback, setFeedbackStatus, getFeedbackAttachment, getFeedbackReplies, updateFeedback, deleteFeedback, updateFeedbackReply, deleteFeedbackReply } from "../feedbackController.js";
const router = express.Router();
router.use("/feedback", verifyUser, verifyRole(["employer", "department_head", "admin"]));
router.get("/feedback/interns", generalLimiter, getFeedbackInterns);
router.get("/feedback", generalLimiter, listFeedback);
router.post("/feedback", verifyRole(["employer"]), uploadLimiter, acceptFeedbackAttachments, createFeedback);
router.get("/feedback/:id", generalLimiter, getFeedback);
router.patch("/feedback/:id", verifyRole(["employer"]), uploadLimiter, acceptFeedbackAttachments, updateFeedback);
router.delete("/feedback/:id", verifyRole(["employer"]), mediumLimiter, deleteFeedback);
router.get("/feedback/:id/replies", generalLimiter, getFeedbackReplies);
router.post("/feedback/:id/replies", mediumLimiter, replyFeedback);
router.patch("/feedback/:id/replies/:replyId", mediumLimiter, updateFeedbackReply);
router.delete("/feedback/:id/replies/:replyId", mediumLimiter, deleteFeedbackReply);
router.patch("/feedback/:id/status", mediumLimiter, setFeedbackStatus);
router.get("/feedback/:id/attachments/:attachmentId", generalLimiter, getFeedbackAttachment);
export default router;
